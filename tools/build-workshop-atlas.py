"""
Packs the Ultimate Isometric Pack "placeable items" used in the workshop into one atlas:
  public/images/base/items.png
  src/game/world/workshopAtlas.ts   (frame rectangles, [x, y, w, h])
Run from the project root:  python3 tools/build-workshop-atlas.py
"""
import json
import os
from PIL import Image

ROOT = "src/assets/Ultimate_Isometric_Pack (1)/PlacebleItems/"
ITEMS = {
    "chest_wood": "Wood_Chest", "chest_dark": "DarkWood_Chest", "chest_light": "LightWood_Chest", "chest_fantasy": "FantasyWood_Chest",
    "crate_wood": "Wood_Crate", "crate_dark": "DarkWood_Crate", "crate_light": "LightWood_Crate", "crate_empty": "Wood_CrateEmpty",
    "furnace": "Metal_Furnace", "bucket": "Bucket", "bucket_water": "Bucket_Water", "lantern": "Lantern_On",
    "log": "Wood_Log", "board": "Board", "pole": "Wood_Pole", "round": "Wood_Round", "oldlog": "Wood_OldLog",
    "hammer": "Iron_Hammer", "axe": "Iron_Axe", "pickaxe": "Iron_PickAxe", "shovel": "Iron_Showel",
    "stone_brick": "Stone_Brick", "mortar": "Stone_Morter", "nails": "Metal_Nails", "brush": "Paint_Brush",
    "plant": "PottedPlant", "teapot": "Teapot_Clay", "jar": "Jar", "candle": "Candle", "bottle": "Bottle_GreenLiquid",
    "sword": "Iron_Sword", "shield": "Iron_Shield",
}

def find(stem):
    for d in sorted(os.listdir(ROOT)):
        p = f"{ROOT}{d}/{stem}.png"
        if os.path.exists(p):
            return p
    raise SystemExit(f"missing {stem}")

sprites = {name: Image.open(find(stem)).convert("RGBA") for name, stem in ITEMS.items()}
frames, x, y, shelf = {}, 0, 0, 0
for name, im in sprites.items():
    if x + im.width > 2048:
        x, y, shelf = 0, y + shelf, 0
    frames[name] = [x, y, im.width, im.height]
    x += im.width
    shelf = max(shelf, im.height)
sheet = Image.new("RGBA", (2048, y + shelf), (0, 0, 0, 0))
for name, (fx, fy, _, _) in frames.items():
    sheet.paste(sprites[name], (fx, fy))
os.makedirs("public/images/base", exist_ok=True)
sheet.save("public/images/base/items.png", optimize=True)
with open("src/game/world/workshopAtlas.ts", "w") as f:
    f.write("/** Generated by tools/build-workshop-atlas.py — do not edit. [x, y, w, h] in items.png. */\n")
    f.write("export const ITEM_FRAMES: Record<string, [number, number, number, number]> = " + json.dumps(frames, indent=4) + ";\n")
print(len(frames), "items,", sheet.size)
