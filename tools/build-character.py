"""
Converts the Character0 spritesheets (460 px cells, 5 facing rows) for the game:
  public/images/world/char/<key>.png   (pre-scaled, palette-compressed)
  src/game/world/characterAtlas.ts     (frame counts per sheet)
Rows are facings: 0 front, 1 front-left, 2 left, 3 back-left, 4 back; right-facing
directions mirror rows 1-3. A sheet key is "<action>" or "<action>:<tool>".
Run from the project root:  python3 tools/build-character.py
"""
import os
import re
from PIL import Image

SRC = "src/assets/Character0/"
OUT = "public/images/world/char/"
CELL_SRC = 460
CELL = 180
K = CELL / CELL_SRC
FEET = (229, 439)  # feet (x centre, y) inside a source cell, measured over all frames

ACTIONS = {"Idle": "idle", "Walk": "walk", "Run": "run", "Interact": "interact", "Swing": "swing",
           "SwordAttack": "attack", "Dig": "dig", "Fish": "fish", "Sit": "sit", "GetUp": "getup",
           "Damage": "damage", "Die": "die"}
TOOLS = {"axe": "axe", "hammer": "hammer", "pickaxe": "pickaxe", "shield": "shield", "showel": "shovel",
         "sword": "sword", "watercan": "watercan", "fishingpole": "fishingpole", "silver": "silver"}

os.makedirs(OUT, exist_ok=True)
sheets = {}
for fname in sorted(os.listdir(SRC)):
    m = re.match(r"Character0_([A-Za-z]+?)(HoldingTool)?(?:_([A-Za-z]+))?\.png$", fname)
    if not m:
        continue
    act, holding, tool = m.groups()
    action = ACTIONS[act]
    if tool:
        tool = TOOLS[tool.lower()]
    elif holding:
        tool = "hold"
    key = f"{action}:{tool}" if tool else action
    im = Image.open(SRC + fname).convert("RGBA")
    cols, rows = im.width // CELL_SRC, im.height // CELL_SRC
    assert rows == 5, fname
    small = im.resize((cols * CELL, rows * CELL), Image.LANCZOS)
    small.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(
        OUT + key.replace(":", "-") + ".png", optimize=True)
    sheets[key] = cols

with open("src/game/world/characterAtlas.ts", "w") as f:
    f.write("/** Generated by tools/build-character.py — do not edit. */\n")
    f.write(f"export const CHAR_CELL = {CELL};\n")
    f.write(f"export const CHAR_FEET_X = {round(FEET[0] * K)};\n")
    f.write(f"export const CHAR_FEET_Y = {round(FEET[1] * K)};\n")
    f.write("/** Frames per row for each sheet; the file is images/world/char/<key with ':' as '-'>.png. */\n")
    f.write("export const CHAR_SHEETS: Record<string, number> = {\n")
    for k, v in sheets.items():
        f.write(f"    '{k}': {v},\n")
    f.write("};\n")
total = sum(os.path.getsize(OUT + n) for n in os.listdir(OUT))
print(len(sheets), "sheets,", round(total / 1e6, 2), "MB")
