"""
Finds where the character's sword is in every animation frame, by comparing each animation sheet
drawn with the sword against the same animation without it. For each (animation, facing row, frame)
it records the grip point (hand end of the blade), the blade direction and length, in the 180 px
cell space the game uses, so any other sword picture can be drawn in the same place:
  src/game/world/swordPose.ts
Run from the project root:  python3 tools/extract-sword-poses.py
"""
import json
import math
import os
import numpy as np
from PIL import Image

SRC = "src/assets/Character0/Character0_"
CELL = 460
K = 180 / CELL
PAIRS = {
    "idle": ("IdleHoldingTool_Sword", "IdleHoldingTool"),
    "walk": ("WalkHoldingTool_Sword", "WalkHoldingTool"),
    "run": ("Run_Sword", "Run"),
    "attack": ("SwordAttack_Sword", "SwordAttack"),
    "interact": ("InteractHoldingTool_Sword", "InteractHoldingTool"),
    "damage": ("DamageHoldingTool_Sword", "DamageHoldingTool"),
    "getup": ("GetUpHoldingTool_Sword", "GetUpHoldingTool"),
    "sit": ("SitHoldingTool_Sword", "SitHoldingTool"),
}
out, report = {}, []
for key, (sw, base) in PAIRS.items():
    A = np.array(Image.open(f"{SRC}{sw}.png").convert("RGBA")).astype(int)
    B = np.array(Image.open(f"{SRC}{base}.png").convert("RGBA")).astype(int)
    cols = A.shape[1] // CELL
    rows = []
    for r in range(5):
        row = []
        for c in range(cols):
            a = A[r * CELL:(r + 1) * CELL, c * CELL:(c + 1) * CELL]
            b = B[r * CELL:(r + 1) * CELL, c * CELL:(c + 1) * CELL]
            diff = (np.abs(a - b).sum(axis=2) > 40) & (a[:, :, 3] > 40)
            ys, xs = np.nonzero(diff)
            if len(xs) < 60:
                row.append(None)
                continue
            body_y, body_x = np.nonzero(b[:, :, 3] > 40)
            bc = np.array([body_x.mean(), body_y.mean()])
            pts = np.stack([xs, ys], 1).astype(float)
            mean = pts.mean(0)
            u, s, vt = np.linalg.svd(pts - mean, full_matrices=False)
            axis = vt[0]
            proj = (pts - mean) @ axis
            lo, hi = pts[proj.argmin()], pts[proj.argmax()]
            # the tip is the end farther from the body
            tip, grip = (hi, lo) if np.linalg.norm(hi - bc) >= np.linalg.norm(lo - bc) else (lo, hi)
            # the blade is the long, thin part: use the 8 % - 92 % extent to ignore stray hand pixels
            ext = np.percentile(proj, [4, 96])
            length = float(ext[1] - ext[0])
            # grip = the end of that extent nearest the hand
            d = tip - grip
            ang = math.degrees(math.atan2(d[1], d[0]))
            row.append([round(grip[0] * K, 1), round(grip[1] * K, 1), round(ang, 1), round(length * K, 1)])
        rows.append(row)
    out[key] = rows
    ok = sum(1 for r in rows for f in r if f)
    report.append((key, ok, sum(len(r) for r in rows)))
print(report)
with open("src/game/world/swordPose.ts", "w") as f:
    f.write("/** Generated by tools/extract-sword-poses.py — do not edit.\n * SWORD_POSE[animation][facing row][frame] = [grip x, grip y, blade angle in degrees (screen, 0 = right), blade length]\n * in the 180 px character cell, or null when no sword shows in that frame. */\n")
    f.write("export const SWORD_POSE: Record<string, ([number, number, number, number] | null)[][]> = " + json.dumps(out) + ";\n")

# ---- The sword sheet: where each sword's hilt end and tip are (src/assets/File.png, 6 x 5 cells of 32 px).
sheet = np.array(Image.open("src/assets/File.png").convert("RGBA"))
native = []
for idx in range(30):
    cx, cy = (idx % 6) * 32, (idx // 6) * 32
    alpha = sheet[cy:cy + 32, cx:cx + 32, 3] > 40
    # the largest connected piece is the sword; sparkles and flames floating away from it are ignored
    seen = np.zeros_like(alpha)
    best = []
    for y0, x0 in zip(*np.nonzero(alpha)):
        if seen[y0, x0]:
            continue
        comp, stack = [], [(y0, x0)]
        seen[y0, x0] = True
        while stack:
            y, x = stack.pop()
            comp.append((x, y))
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    ny, nx = y + dy, x + dx
                    if 0 <= ny < 32 and 0 <= nx < 32 and alpha[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True
                        stack.append((ny, nx))
        if len(comp) > len(best):
            best = comp
    pts = np.array(best, dtype=float)
    # swords run from the top-left (tip) to the bottom-right (hilt)
    along = (-pts[:, 0] - pts[:, 1]) / math.sqrt(2)
    across = (pts[:, 0] - pts[:, 1]) / math.sqrt(2)
    lo, hi = along.min(), along.max()
    mid = across.mean()
    at = lambda t: ((-t + mid) / math.sqrt(2), (-t - mid) / math.sqrt(2))
    tip, hilt = at(hi), at(lo)
    native.append([round(hilt[0], 1), round(hilt[1], 1), round(tip[0], 1), round(tip[1], 1)])
with open("src/game/world/swordNative.ts", "w") as f:
    f.write("/** Generated by tools/extract-sword-poses.py — do not edit.\n * SWORD_NATIVE[i] = [hilt x, hilt y, tip x, tip y] inside sword i's 32 px cell of public/images/swords.png. */\n")
    f.write("export const SWORD_NATIVE: [number, number, number, number][] = " + json.dumps(native) + ";\n")
print("sword sheet measured:", native[:3])
