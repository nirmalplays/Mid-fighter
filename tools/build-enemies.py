"""
Converts the IsometricEnemies sheets (460 px cells, 5 facing rows like Character0) used by
the game's monsters, pre-scaled and palette-compressed:
  public/images/world/enemy/<kind>-<move|attack|die>.png
  src/game/world/enemyAtlas.ts   (frames per sheet and each enemy's feet position)
Run from the project root:  python3 tools/build-enemies.py
"""
import os
import numpy as np
from PIL import Image

SRC = "src/assets/IsometricEnemies 2/"
OUT = "public/images/world/enemy/"
CELL_SRC = 460
CELL = 180
K = CELL / CELL_SRC

# kind -> (folder, file stem pattern with {anim})
KINDS = {
    "goblin": ("Goblin", "Goblin1_{anim}"),
    "slime": ("Slime", "Slime_{anim}_Green"),
    "wolf": ("Wolf", "Wolf_{anim}_Grey"),
    "skeleton": ("Skeleton", "Skeleton1_{anim}"),
}
ANIMS = {"move": "Move", "attack": "Attack", "die": "Die"}

os.makedirs(OUT, exist_ok=True)
frames, feet = {}, {}
for kind, (folder, pattern) in KINDS.items():
    fx, fy = [], []
    for key, anim in ANIMS.items():
        im = Image.open(f"{SRC}{folder}/{pattern.format(anim=anim)}.png").convert("RGBA")
        cols, rows = im.width // CELL_SRC, im.height // CELL_SRC
        assert rows == 5, (kind, key, rows)
        frames[f"{kind}-{key}"] = cols
        if key == "move":  # measure feet over all facings and frames of the walk
            a = np.array(im)[:, :, 3]
            for r in range(5):
                for c in range(cols):
                    cell = a[r * CELL_SRC:(r + 1) * CELL_SRC, c * CELL_SRC:(c + 1) * CELL_SRC]
                    ys, xs = np.where(cell > 20)
                    if len(ys):
                        fy.append(ys.max())
                        fx.append((xs.min() + xs.max()) / 2)
        small = im.resize((cols * CELL, rows * CELL), Image.LANCZOS)
        small.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(
            f"{OUT}{kind}-{key}.png", optimize=True)
    feet[kind] = (round(float(np.median(fx)) * K), round(float(np.median(fy)) * K))

with open("src/game/world/enemyAtlas.ts", "w") as f:
    f.write("/** Generated by tools/build-enemies.py — do not edit. */\n")
    f.write(f"export const ENEMY_CELL = {CELL};\n")
    f.write("/** Frames per row for each sheet; the file is images/world/enemy/<key>.png. */\n")
    f.write("export const ENEMY_SHEETS: Record<string, number> = {\n")
    for k, v in frames.items():
        f.write(f"    '{k}': {v},\n")
    f.write("};\n/** Feet position (x centre, y) inside a cell, per kind. */\n")
    f.write("export const ENEMY_FEET: Record<string, [number, number]> = {\n")
    for k, (x, y) in feet.items():
        f.write(f"    {k}: [{x}, {y}],\n")
    f.write("};\n")
total = sum(os.path.getsize(OUT + n) for n in os.listdir(OUT))
print(len(frames), "sheets", round(total / 1e6, 2), "MB; feet", feet)
