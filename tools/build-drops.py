"""
Scales the gems used as monster drops into one small atlas:
  public/images/world/drops.png
  src/game/world/dropsAtlas.ts   ([x, y, w, h] per drop)
Run from the project root:  python3 tools/build-drops.py
"""
import json
from PIL import Image

ROOT = "src/assets/Ultimate_Isometric_Pack (1)/PlacebleItems/Valuables/"
DROPS = {"attack": "Ruby", "defence": "LapisLazulie", "speed": "Emrald", "vitality": "Amber"}
H = 64
ims = {}
for name, stem in DROPS.items():
    im = Image.open(f"{ROOT}{stem}.png").convert("RGBA")
    im = im.crop(im.getbbox())
    ims[name] = im.resize((max(1, round(im.width * H / im.height)), H), Image.LANCZOS)
frames, x = {}, 0
for name, im in ims.items():
    frames[name] = [x, 0, im.width, im.height]
    x += im.width + 2
sheet = Image.new("RGBA", (x, H), (0, 0, 0, 0))
for name, (fx, fy, _, _) in frames.items():
    sheet.paste(ims[name], (fx, fy))
sheet.save("public/images/world/drops.png", optimize=True)
with open("src/game/world/dropsAtlas.ts", "w") as f:
    f.write("/** Generated by tools/build-drops.py — do not edit. [x, y, w, h] in drops.png. */\n")
    f.write("export const DROP_FRAMES: Record<string, [number, number, number, number]> = " + json.dumps(frames, indent=4) + ";\n")
print(frames)
