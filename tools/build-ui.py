"""
Prepares the UI Asset Pack pieces the menu uses:
  public/images/ui/btn<1-3>-<normal|hover|pressed>.png   (cropped to the 9-slice bounds)
  public/images/ui/frame<N>.png                           (panel frames, cropped the same way)
  public/images/ui/icons.png                              (13 icons, 16 px each: white with outline)
  src/ui/uiSlices.ts                                      (stretch insets per piece, from the pack's Aseprite json)
Run from the project root:  python3 tools/build-ui.py
"""
import json
import os
from PIL import Image

SRC = "src/assets/UI Asset Pack/UI Asset Pack/"
OUT = "public/images/ui/"
os.makedirs(OUT, exist_ok=True)
slices = {}

def piece(name, png, js):
    meta = json.load(open(js))
    key = meta["meta"]["slices"][0]["keys"][0]
    b, c = key["bounds"], key["center"]
    im = Image.open(png).convert("RGBA").crop((b["x"], b["y"], b["x"] + b["w"], b["y"] + b["h"]))
    im.save(f"{OUT}{name}.png", optimize=True)
    # insets: left, top, right, bottom
    slices[name] = [c["x"], c["y"], b["w"] - c["x"] - c["w"], b["h"] - c["y"] - c["h"], b["w"], b["h"]]

for n in (1, 2, 3):
    for st in ("normal", "hover", "pressed"):
        base = f"{SRC}9slices/Buttons/button_0{n}_{st}_9slice"
        png = base + ".png" if os.path.exists(base + ".png") else base + "-sheet.png"
        piece(f"btn{n}-{st}", png, base + ".json")
for n in range(1, 8):
    base = f"{SRC}9slices/Frames/frame_0{n}_9slice"
    piece(f"frame{n}", base + ".png", base + ".json")

Image.open(f"{SRC}Icons/Icon_03_strip13.png").convert("RGBA").save(OUT + "icons.png", optimize=True)

with open("src/ui/uiSlices.ts", "w") as f:
    f.write("/** Generated by tools/build-ui.py — do not edit. [left, top, right, bottom insets, width, height] per piece. */\n")
    f.write("export const UI_SLICES: Record<string, [number, number, number, number, number, number]> = " + json.dumps(slices, indent=4) + ";\n")
print(len(slices), "pieces")
for k in ("btn1-normal", "btn3-normal", "frame5", "frame6"):
    print(k, slices[k])
